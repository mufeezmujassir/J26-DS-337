"""Build the frozen disruption-detection dataset from real public data.

The pipeline mirrors the six documented stages:

1. Load the raw sources (``sri_lankan_attractions.jsonl`` and
   ``weather_monthly.jsonl``).
2. Sample 3,000 scenarios, grounding weather/outdoor features in real records.
3. Derive the remaining signals with a seeded RNG.
4. Label every scenario with the deterministic rules, balance to the target
   class distribution, then flip 5% of the labels.
5. Split 80/10/10, stratified by ``(label, severity)``.
6. Persist the dataset, the ``metadata.json`` manifest and a README.

The feature schema, label vocabulary and file names are identical to the
previous (fully synthetic) generator, so the training, inference and
evaluation scripts consume the output unchanged.
"""

from __future__ import annotations

import argparse
import logging
import random
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Sequence, Tuple

# Allow direct script execution as well as module import.
if __package__ in (None, ""):  # pragma: no cover - script execution path
    sys.path.insert(0, str(Path(__file__).resolve().parents[4]))

from app.replanning.disruption_detection.classifiers import (  # noqa: E402
    DATA_DIR,
    FEATURE_NAMES,
    LABEL_DISRUPTION,
    LABEL_NORMAL,
    RAW_DIR,
    SEVERITY_LEVELS,
    SEVERITY_NONE,
)
from app.replanning.disruption_detection.classifiers._dataset_io import (  # noqa: E402
    compute_sha256,
    save_jsonl,
    stratified_split,
    write_metadata,
)
from app.replanning.disruption_detection.classifiers._disruption_labeler import (  # noqa: E402
    DisruptionLabeler,
)
from app.replanning.disruption_detection.classifiers._feature_sampler import (  # noqa: E402
    FeatureSampler,
)

LOGGER = logging.getLogger("build_disruption_dataset")

BUILDER_VERSION = "1.0.0"
DEFAULT_SEED = 42
DEFAULT_TOTAL_ROWS = 3000
LABEL_NOISE_RATE = 0.05

# Oversample factor; the pool is labelled, then trimmed to the target counts.
POOL_FACTOR = 6

ATTRACTIONS_FILE = "sri_lankan_attractions.jsonl"
WEATHER_FILE = "weather_monthly.jsonl"

# Target class distribution before label noise is applied.
TARGET_DISTRIBUTION: Dict[Tuple[str, str], float] = {
    (LABEL_NORMAL, SEVERITY_NONE): 0.40,
    (LABEL_DISRUPTION, "step"): 0.30,
    (LABEL_DISRUPTION, "day"): 0.20,
    (LABEL_DISRUPTION, "plan"): 0.10,
}


def _allocate_targets(total_rows: int) -> Dict[Tuple[str, str], int]:
    """Split ``total_rows`` across the target classes (largest remainders)."""
    keys = sorted(TARGET_DISTRIBUTION)
    ratios = [TARGET_DISTRIBUTION[key] for key in keys]
    raw = [ratio * total_rows for ratio in ratios]
    counts = [int(value) for value in raw]
    remainder = total_rows - sum(counts)

    order = sorted(
        range(len(keys)),
        key=lambda index: (-(raw[index] - counts[index]), index),
    )
    for index in order[:remainder]:
        counts[index] += 1
    return {key: count for key, count in zip(keys, counts)}


def _select_balanced(
    pool: Sequence[Dict[str, Any]],
    total_rows: int,
    seed: int,
) -> List[Dict[str, Any]]:
    """Reduce a labelled pool to ``total_rows`` matching the target mix."""
    rng = random.Random(seed + 2)
    targets = _allocate_targets(total_rows)

    by_class: Dict[Tuple[str, str], List[Dict[str, Any]]] = {}
    for row in pool:
        by_class.setdefault((row["label"], row["severity"]), []).append(row)

    selected: List[Dict[str, Any]] = []
    leftover: List[Dict[str, Any]] = []
    for key, count in targets.items():
        bucket = by_class.get(key, [])[:]
        rng.shuffle(bucket)
        take = min(count, len(bucket))
        if take < count:
            LOGGER.warning(
                "Only %d/%d scenarios available for class %s; "
                "increase POOL_FACTOR to avoid a skewed distribution.",
                take,
                count,
                key,
            )
        selected.extend(bucket[:take])
        leftover.extend(bucket[take:])

    deficit = total_rows - len(selected)
    if deficit > 0:
        rng.shuffle(leftover)
        selected.extend(leftover[:deficit])

    rng.shuffle(selected)
    return selected


def _count(rows: Sequence[Dict[str, Any]], field: str) -> Dict[str, int]:
    counts: Dict[str, int] = {}
    for row in rows:
        value = str(row.get(field, SEVERITY_NONE))
        counts[value] = counts.get(value, 0) + 1
    return counts


def _render_readme(metadata: Dict[str, Any]) -> str:
    return f"""# Disruption Detection Dataset (real-data supported)

Generated by `build_disruption_dataset.py` (builder **{metadata["builder_version"]}**).

## Provenance

The weather and outdoor features are grounded in real public data:

* `../raw/{ATTRACTIONS_FILE}` -- real Sri Lankan attractions (district,
  category, outdoor flag, coordinates, etc.).
* `../raw/{WEATHER_FILE}` -- real monthly weather per district (rainfall and
  maximum temperature).

Only attractions whose district has weather coverage are sampled, so:

* rows backed by real weather: **{metadata["rows_with_real_weather"]}**
* rows backed by real attractions: **{metadata["rows_with_real_attractions"]}**
* `real_data_ratio`: **{metadata["real_data_ratio"]}**

The remaining signals (closure, capacity, crowds, complaints, change requests,
GPS deviation, delay, affected activities) are not observable in the raw
sources and are drawn with a seeded RNG (seed `{metadata["random_seed"]}`).

## Files

| File | Rows | Purpose |
| --- | --- | --- |
| `simulated_disruptions.jsonl` | {metadata["num_rows"]} | Full frozen dataset |
| `train.jsonl` | {metadata["train_rows"]} | Training split (80%) |
| `dev.jsonl` | {metadata["dev_rows"]} | Validation split (10%) |
| `test.jsonl` | {metadata["test_rows"]} | Test split (10%) |
| `metadata.json` | - | Manifest (hashes + distributions) |

## Schema

Every row carries the 13 model features plus `label`, `severity` and
provenance fields (`attraction_id`, `district`, `district_id`, `month`,
`category`, `is_real_weather`, `is_real_attraction`):

| Feature | Source |
| --- | --- |
| `rain_duration_hours` | real monthly rainfall |
| `rain_intensity_score` | real monthly rainfall (normalised) |
| `temperature_celsius` | real monthly max temperature |
| `heat_warning` | real monthly max temperature (> 35 C) |
| `is_outdoor_activity` | real attraction record |
| `closure_flag` | seeded RNG |
| `capacity_issue` | seeded RNG |
| `crowd_level_score` | seeded RNG |
| `complaint_score` | seeded RNG |
| `change_request` | seeded RNG |
| `gps_deviation_km` | seeded RNG |
| `time_delay_minutes` | seeded RNG |
| `num_affected_activities` | seeded RNG |

## Labels

`label` is `normal` or `disruption`; `severity` is `none` (for normal rows) or
one of `step` / `day` / `plan`. Labels are produced by the deterministic rules
in `_disruption_labeler.py`, balanced to a 40/30/20/10 target, then 5% of the
labels are flipped to emulate noisy supervision.

* label distribution: `{metadata["label_distribution"]}`
* severity distribution: `{metadata["severity_distribution"]}`

## Reproduce

```bash
python -m app.replanning.disruption_detection.classifiers.build_disruption_dataset
```

The pipeline is fully deterministic for a given `--seed`.
"""


def build_dataset(
    raw_dir: str | Path = RAW_DIR,
    output_dir: str | Path = DATA_DIR,
    total_rows: int = DEFAULT_TOTAL_ROWS,
    seed: int = DEFAULT_SEED,
) -> Dict[str, Any]:
    """Run the full pipeline and return the metadata manifest."""
    raw_dir = Path(raw_dir)
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    # Stage 1 -- load real sources.
    sampler = FeatureSampler(
        raw_dir / ATTRACTIONS_FILE,
        raw_dir / WEATHER_FILE,
        seed=seed,
    )
    sampler.load_sources()

    # Stage 2 -- sample a scenario pool grounded in real data.
    pool = sampler.sample_batch(total_rows * POOL_FACTOR)
    LOGGER.info("Sampled %d candidate scenarios", len(pool))

    # Stage 3/4 -- label the pool and balance to the target distribution.
    labeler = DisruptionLabeler(noise_rate=LABEL_NOISE_RATE, seed=seed)
    for row in pool:
        label, severity = labeler.label(row)
        row["label"] = label
        row["severity"] = severity

    rows = _select_balanced(pool, total_rows, seed)
    LOGGER.info("Selected %d balanced scenarios", len(rows))

    flips = labeler.apply_noise_to_rows(rows)
    LOGGER.info(
        "Applied %d label-noise flips (%.0f%%)", flips, LABEL_NOISE_RATE * 100
    )

    # Stage 5 -- stratified split.
    train, dev, test = stratified_split(
        rows, train_ratio=0.8, dev_ratio=0.1, test_ratio=0.1, seed=seed
    )

    # Stage 6 -- persist.
    dataset_path = save_jsonl(rows, output_dir / "simulated_disruptions.jsonl")
    save_jsonl(train, output_dir / "train.jsonl")
    save_jsonl(dev, output_dir / "dev.jsonl")
    save_jsonl(test, output_dir / "test.jsonl")

    severity_counts = _count(rows, "severity")
    severity_distribution = {
        level: severity_counts.get(level, 0) for level in SEVERITY_LEVELS
    }
    label_counts = _count(rows, "label")
    label_distribution = {
        LABEL_NORMAL: label_counts.get(LABEL_NORMAL, 0),
        LABEL_DISRUPTION: label_counts.get(LABEL_DISRUPTION, 0),
    }

    rows_with_real_weather = sum(
        1 for row in rows if row.get("is_real_weather")
    )
    rows_with_real_attractions = sum(
        1 for row in rows if row.get("is_real_attraction")
    )
    source_attractions_count = len(
        {row.get("attraction_id") for row in rows}
    )
    source_districts_count = len({row.get("district_id") for row in rows})

    metadata: Dict[str, Any] = {
        "builder_version": BUILDER_VERSION,
        "random_seed": seed,
        "num_rows": len(rows),
        "rows_with_real_weather": rows_with_real_weather,
        "rows_with_real_attractions": rows_with_real_attractions,
        "real_data_ratio": round(rows_with_real_weather / len(rows), 4)
        if rows
        else 0.0,
        "train_rows": len(train),
        "dev_rows": len(dev),
        "test_rows": len(test),
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "label_distribution": label_distribution,
        "severity_distribution": severity_distribution,
        "source_attractions_count": source_attractions_count,
        "source_districts_count": source_districts_count,
        "dataset_hash_sha256": compute_sha256(dataset_path),
        "feature_names": list(FEATURE_NAMES),
    }

    write_metadata(metadata, output_dir / "metadata.json")
    (output_dir / "README.md").write_text(
        _render_readme(metadata), encoding="utf-8"
    )
    LOGGER.info("Dataset written to %s", output_dir)
    return metadata


def parse_args(argv: List[str] | None = None) -> argparse.Namespace:
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(
        description="Build the disruption-detection dataset from real data.",
    )
    parser.add_argument(
        "--raw-dir",
        default=str(RAW_DIR),
        help="Directory holding the raw source JSONL files "
        "(default: data/disruption_detection/raw).",
    )
    parser.add_argument(
        "--output-dir",
        default=str(DATA_DIR),
        help="Directory to write the dataset into "
        "(default: data/disruption_detection/processed).",
    )
    parser.add_argument(
        "--total-rows",
        type=int,
        default=DEFAULT_TOTAL_ROWS,
        help=f"Number of rows to build (default: {DEFAULT_TOTAL_ROWS}).",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=DEFAULT_SEED,
        help=f"Random seed (default: {DEFAULT_SEED}).",
    )
    return parser.parse_args(argv)


def main(argv: List[str] | None = None) -> int:
    """Entry point: build and persist the dataset."""
    args = parse_args(argv)
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s - %(name)s - %(levelname)s - %(message)s",
    )

    raw_dir = Path(args.raw_dir)
    if not raw_dir.is_absolute():
        raw_dir = Path.cwd() / raw_dir
    output_dir = Path(args.output_dir)
    if not output_dir.is_absolute():
        output_dir = Path.cwd() / output_dir

    metadata = build_dataset(
        raw_dir=raw_dir,
        output_dir=output_dir,
        total_rows=args.total_rows,
        seed=args.seed,
    )

    LOGGER.info(
        "Dataset ready: rows=%d real_data_ratio=%.2f normal=%d "
        "disruption=%d severity=%s hash=%s",
        metadata["num_rows"],
        metadata["real_data_ratio"],
        metadata["label_distribution"][LABEL_NORMAL],
        metadata["label_distribution"][LABEL_DISRUPTION],
        metadata["severity_distribution"],
        metadata["dataset_hash_sha256"][:12],
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
